'use strict';
/**
 * Card component, drawn with the original 1.7.4 client's textures (assets/orig/ui, docs/design/apk-assets.md).
 * renderCard(cardView, opts) draws a card in one of four sizes:
 *  - compact (120x168): collection grid - art under the tinted cardframe, stats band (cardstatsoverlay) with
 *                       ATK/mana over HP/ability, star + "Level n / max" bar, "in deck" fan (cardindeck)
 *  - battle  (116x164): line-ups - art, stats band (cardstatsoverlay_small) on the edge away from the enemy
 *                       (sword/star over heart/anvil), direction arrows on the edge facing the enemy,
 *                       optional HP bar outside the card
 *  - detail  (600 wide): carddetail_top_<rarity> plate (name, tribe emblem), art between the rarity rails,
 *                       carddetail_bottom_<rarity> plate (rarity label, 5 crystal pips, level bar), then the
 *                       stats panel (sword/heart/mana, ability text) and the zoom / sell buttons
 *  - back    (116x164): face-down card: cardslot{dwarf,elf,ork,neutral}_thumb (or the "?" thumb)
 *
 * cardView = { name, tribe, rarity, stage, level, levelCap, attack, hp, maxHp, abilityValue, abilityText,
 *              mana, dirs, healDirs, buffDirs, artUrl, artFallbackUrl, pips, xp, xpToNext, uid, cardId }
 *
 * Sprite mapping: frame = cardframe_<rarity> (cardframe.png tinted, exploration/tools/make-card-frames.py); stats icons =
 * hud_fighticon02 (sword), hud_healthicon01 (heart), hud_experienceicon01 (star), hud_specialskill01 (anvil),
 * hud_manaicon01 (drop); arrows = card_arrowred01 (attack), card_arrow01 (heal, green), card_arrowblue01 (buff);
 * tribe emblems = hud_{dwarf,elf,orc,neutral}icon01; pips = hud_evolution / hud_evolution_grey; in-deck =
 * cardindeck; locked = lock_big; dead = burnedcard; pieces = piece{2,4,6,10}_N / _Nb; empty slot =
 * cardslot_simple, locked slot = cardslotlocked; zoom / sell buttons = button_zoom / button_sell.
 */
import { h, icon, fmt, iconUrl, spriteUrl } from '../dom.js';
import { levelBar } from './bars.js';
import { iconButton } from './buttons.js';
import { RARITY_ORDER, TRIBE_ORDER } from '../../core/constants.js';

const PLACEHOLDER_ART = iconUrl('card-placeholder');

/** Original sprites of the stat icons. */
const STAT_SPRITES = Object.freeze({
  attack: 'hud_fighticon02', hp: 'hud_healthicon01', star: 'hud_experienceicon01', ability: 'hud_specialskill01', mana: 'hud_manaicon01',
});
/** Original tribe emblems (the octagon box of the detail plate, filter chips, card backs' fallback). */
export const TRIBE_SPRITES = Object.freeze({ dwarf: 'hud_dwarficon01', elf: 'hud_elficon01', orc: 'hud_orcicon01', neutral: 'hud_neutralicon01' });
/** Face-down card thumbs by tribe (+ the "?" thumb for a hidden card). */
const BACK_SPRITES = Object.freeze({
  dwarf: 'cardslotdwarf_thumb', elf: 'cardslotelf_thumb', orc: 'cardslotork_thumb', neutral: 'cardslotneutral_thumb', unknown: 'cardslot_question01_thumb',
});
/** Direction arrows: attack (red), heal (green), buff / magic (blue). */
const ARROW_SPRITES = Object.freeze({ attack: 'card_arrowred01', heal: 'card_arrow01', buff: 'card_arrowblue01' });
/** Detail action buttons: icon name (buttons.js) -> original sprite. */
const ACTION_SPRITES = Object.freeze({ magnifier: 'button_zoom', dollar: 'button_sell' });

/**
 * Reveal glow sprite (glowingcard / glowingcardblue / glowingcardred) for a rarity.
 * @param {string} rarity
 * @returns {string}
 */
export function glowSpriteFor(rarity) {
  if (rarity === 'ultimate') return 'glowingcardred';
  if (rarity === 'rare' || rarity === 'heroic') return 'glowingcardblue';
  return 'glowingcard';
}

/** Size of the card canvas the puzzle-piece sprites were cut from. */
export const PIECE_CANVAS = Object.freeze([451, 640]);
/**
 * [x, y, w, h] of piece<n>_<i+1>.png on the 451x640 card canvas (generated by exploration/tools/make-card-frames.py,
 * which fits the silhouettes together; the sprite sheets carry no offsets).
 */
export const PIECE_LAYOUTS = Object.freeze({
  2: [[0, 0, 451, 323], [0, 217, 451, 423]],
  4: [[0, 0, 300, 323], [223, 0, 228, 394], [0, 246, 229, 394], [152, 314, 299, 326]],
  6: [[0, 0, 280, 216], [223, 0, 228, 216], [0, 159, 229, 282], [172, 159, 279, 282], [0, 385, 280, 255], [223, 385, 228, 255]],
  10: [[0, 0, 150, 216], [93, 0, 221, 216], [258, 0, 193, 216], [0, 159, 124, 302], [68, 159, 212, 302], [222, 159, 168, 302], [333, 159, 118, 302], [0, 405, 150, 235], [93, 405, 221, 235], [258, 405, 193, 235]],
});

/**
 * <img> of an original sprite (classes "icon sprite", unlike dom.sprite).
 * @param {string} name
 * @param {object} [props]
 * @returns {HTMLImageElement}
 */
export function sprite(name, props = {}) {
  return /** @type {HTMLImageElement} */ (h('img', { alt: '', draggable: 'false', ...props, src: spriteUrl(name), class: ['icon', 'sprite', props.class] }));
}

/**
 * Rarity label with a capital ("Uncommon").
 * @param {string} rarity
 * @returns {string}
 */
export function rarityLabel(rarity) {
  const r = String(rarity || 'common');
  return r.charAt(0).toUpperCase() + r.slice(1);
}

/**
 * "Name" + "+" marks for the fusion stage ("Werewolf Dwarf++").
 * @param {string} name
 * @param {number} [stage=0]
 * @returns {string}
 */
export function cardNameWithPlus(name, stage = 0) {
  return String(name) + '+'.repeat(Math.max(0, Math.min(4, stage | 0)));
}

/**
 * Five fusion pips (hud_evolution crystals); lit = stage + 1.
 * @param {number} stage 0..4
 * @param {{small?: boolean}} [opts]
 * @returns {HTMLElement}
 */
export function renderPips(stage, opts = {}) {
  const lit = Math.max(0, Math.min(5, (stage | 0) + 1));
  return h('div.pips', { class: opts.small && 'small', 'aria-label': `Fusion stage ${stage}` },
    Array.from({ length: 5 }, (_, i) => h('span.pip', { class: i < lit && 'lit' })));
}

/**
 * Which piece sprite set draws a hunt of `total` pieces (2, 4, 6 or 10; 12-piece ultimates use the 10 set).
 * @param {number} total
 * @returns {2|4|6|10}
 */
export function pieceSet(total) {
  const t = total | 0;
  return t <= 2 ? 2 : t <= 4 ? 4 : t <= 6 ? 6 : 10;
}

/**
 * How many sprites of the set are lit for `owned` of `total` pieces (proportional when the set is smaller).
 * @param {number} owned
 * @param {number} total
 * @returns {number}
 */
export function litPieces(owned, total) {
  const set = pieceSet(total);
  const t = Math.max(1, total | 0);
  const o = Math.max(0, Math.min(t, owned | 0));
  if (t === set) return o;
  return Math.max(0, Math.min(set, Math.round((o * set) / t)));
}

/**
 * Overlay of puzzle pieces over the art: owned pieces get the white outline (piece<n>_<i>), missing ones the
 * dark silhouette (piece<n>_<i>b). Positions are percentages of the art box, so any card size works.
 * @param {number} owned
 * @param {number} total
 * @returns {HTMLElement}
 */
export function renderPieces(owned, total) {
  const set = pieceSet(total);
  const lit = litPieces(owned, total);
  const [cw, ch] = PIECE_CANVAS;
  const pct = (v) => `${(v * 100).toFixed(3)}%`;
  const layer = h('div.card-pieces', { dataset: { owned: String(owned | 0), total: String(total | 0) }, 'aria-label': `${owned | 0} of ${total | 0} pieces` });
  PIECE_LAYOUTS[set].forEach(([x, y, w, hh], i) => {
    const own = i < lit;
    layer.appendChild(h('span.piece', {
      class: own ? 'owned' : 'missing',
      dataset: { piece: String(i + 1) },
      style: { left: pct(x / cw), top: pct(y / ch), width: pct(w / cw), height: pct(hh / ch), backgroundImage: `url('${spriteUrl(`piece${set}_${i + 1}${own ? '' : 'b'}`)}')` },
    }));
  });
  layer.appendChild(h('span.card-piece-count', null, sprite('cardpiece_icon'), h('span.num', null, `${owned | 0}/${total | 0}`)));
  return layer;
}

/**
 * Arrow element for a direction (original triangle sprites rotated by CSS).
 * @param {'direct'|'left'|'right'|'ownLeft'|'ownRight'} dir
 * @param {'attack'|'heal'|'buff'} kind
 * @returns {HTMLElement}
 */
function arrow(dir, kind) {
  return h('span.arrow', { class: [dir, kind], 'aria-hidden': 'true' }, sprite(ARROW_SPRITES[kind] || ARROW_SPRITES.attack));
}

/**
 * Overlay with the direction arrows: red attack arrows on the enemy edge, green heal / blue buff arrows on the
 * own neighbours (and on the enemy edge for abilities that hit enemies).
 * @param {string[]} dirs
 * @param {string[]} [healDirs]
 * @param {string[]} [buffDirs]
 * @returns {HTMLElement}
 */
function arrowsLayer(dirs, healDirs, buffDirs) {
  const layer = h('div.card-arrows');
  const seen = new Set();
  for (const d of dirs || []) { layer.appendChild(arrow(d, 'attack')); seen.add(d); }
  const add = (list, kind) => {
    for (const d of list || []) {
      const mapped = d === 'left' ? 'ownLeft' : d === 'right' ? 'ownRight' : d;
      const key = `${kind}:${mapped}`;
      if (['ownLeft', 'ownRight', 'direct', 'oppLeft', 'oppRight'].includes(mapped) && !seen.has(key) && !(mapped === 'direct' && seen.has('direct'))) {
        seen.add(key);
        layer.appendChild(arrow(mapped === 'oppLeft' ? 'left' : mapped === 'oppRight' ? 'right' : mapped, kind));
      }
    }
  };
  add(healDirs, 'heal');
  add(buffDirs, 'buff');
  return layer;
}

/**
 * Card art image with placeholder fallback (and stage-art -> base-art fallback when `artFallbackUrl` is given).
 * @param {object} view
 * @returns {HTMLImageElement}
 */
function artImage(view) {
  const img = icon('card-placeholder', { class: 'placeholder', alt: view.name || '' });
  if (view.artUrl) {
    img.classList.remove('placeholder');
    img.src = view.artUrl;
    img.loading = 'lazy';
    img.decoding = 'async';
    let triedFallback = false;
    img.addEventListener('error', () => {
      if (view.artFallbackUrl && !triedFallback) { triedFallback = true; img.src = view.artFallbackUrl; return; }
      img.classList.add('placeholder');
      img.src = PLACEHOLDER_ART;
    });
  }
  return img;
}

/**
 * One cell of a stats band (original icon + number).
 * @param {'attack'|'hp'|'star'|'ability'|'mana'} kind
 * @param {number|string|null|undefined} value
 * @returns {HTMLElement}
 */
/**
 * A number as the original fight screens print it: plain digits, no thousands separator ("11280", "-5172").
 * @param {number} n
 * @returns {string}
 */
export function plainNumber(n) {
  const v = Number(n);
  return Number.isFinite(v) ? String(Math.round(v)) : '-';
}

function stat(kind, value) {
  const empty = value === null || value === undefined;
  // bands show plain numbers like the original ("1230", no thousands separator) to fit 116px cards
  const text = empty ? '' : (typeof value === 'number' ? plainNumber(value) : String(value));
  return h('span.card-stat', { class: [kind, empty && 'empty', text.length >= 5 && 'long'] }, sprite(STAT_SPRITES[kind]), h('span.num', null, text));
}

/**
 * Stats band for battle cards (sword/star over heart/anvil).
 * @param {object} view
 * @param {'top'|'bottom'} side
 * @returns {HTMLElement}
 */
function statsStrip(view, side) {
  return h('div.card-strip', { class: side },
    stat('attack', view.attack),
    stat('star', view.level),
    stat('hp', view.hp !== undefined ? view.hp : view.maxHp),
    stat('ability', view.abilityValue));
}

/**
 * @typedef {object} CardOptions
 * @property {'compact'|'battle'|'detail'|'back'} [size='compact']
 * @property {'top'|'bottom'} [side='bottom']  which row the card sits in (battle); decides band and arrow edges
 * @property {boolean} [interactive]  hover/press affordance + pointer cursor
 * @property {(ev: MouseEvent, view: object) => void} [onClick]
 * @property {boolean} [locked]  grey art + padlock (collections page)
 * @property {boolean} [selected]
 * @property {boolean} [draggable]  marks the card for drag-drop.js (data-draggable, data-uid)
 * @property {boolean} [hpBar]  battle: draw the thin HP bar outside the card (wraps in .card-wrap)
 * @property {boolean} [showStats=true]  detail: draw the stats panel under the card
 * @property {{icon: string, label?: string, onClick: () => void}[]} [actions]  detail: buttons under the stats panel
 * @property {{owned: number, total: number}} [pieces]  puzzle-piece overlay of a card-piece hunt
 * @property {boolean} [hidden]  back: draw the "?" thumb instead of the tribe thumb
 * @property {string} [className]
 */

/**
 * Render a card.
 * For size 'detail' the returned element is a `.card-detail-wrap` holding the card, the stats panel and the actions.
 * For size 'battle' with `hpBar: true` the returned element is a `.card-wrap` holding the HP bar and the card.
 * @param {object} view  cardView (see module doc)
 * @param {CardOptions} [opts]
 * @returns {HTMLElement}
 */
export function renderCard(view, opts = {}) {
  const size = opts.size || 'compact';
  const side = opts.side || 'bottom';
  const rarity = RARITY_ORDER.includes(view.rarity) ? view.rarity : 'common';
  const tribe = TRIBE_ORDER.includes(view.tribe) ? view.tribe : 'neutral';
  const stage = view.stage | 0;

  const card = h('div.card', {
    class: [`size-${size}`, `side-${side}`, `rarity-${rarity}`, `tribe-${tribe}`,
      opts.interactive && 'interactive', opts.locked && 'locked', opts.selected && 'selected', opts.pieces && 'has-pieces', opts.className],
    dataset: {
      uid: view.uid, cardId: view.cardId || view.id, draggable: opts.draggable ? 'true' : undefined,
      rarity, tribe, stage: String(stage),
    },
    role: opts.interactive || opts.onClick ? 'button' : undefined,
    tabIndex: opts.interactive || opts.onClick ? 0 : undefined,
    'aria-label': `${cardNameWithPlus(view.name, stage)}, ${rarityLabel(rarity)} ${tribe}`,
    onClick: opts.onClick ? (ev) => opts.onClick(ev, view) : undefined,
  });

  if (size === 'back') {
    card.appendChild(h('div.card-back', null, sprite(BACK_SPRITES[opts.hidden ? 'unknown' : tribe], { alt: opts.hidden ? 'Hidden card' : `${tribe} card back` })));
    return card;
  }

  if (size === 'compact') {
    card.appendChild(h('div.card-art', null, artImage(view), arrowsLayer(view.dirs, view.healDirs, view.buffDirs)));
    card.appendChild(h('div.card-stats', null,
      stat('attack', view.attack),
      stat('mana', view.mana),
      stat('hp', view.maxHp !== undefined ? view.maxHp : view.hp),
      stat('ability', view.abilityValue)));
    card.appendChild(levelBar({ level: view.level || 1, levelCap: view.levelCap, xp: view.xp, xpToNext: view.xpToNext }));
    if (stage > 0) card.appendChild(h('span.card-pipcount', null, sprite('hud_evolution'), String(stage + 1)));
    if (opts.pieces) card.appendChild(renderPieces(opts.pieces.owned, opts.pieces.total));
    return card;
  }

  if (size === 'battle') {
    card.appendChild(h('div.card-art', null, artImage(view)));
    card.appendChild(arrowsLayer(view.dirs, view.healDirs, view.buffDirs));
    card.appendChild(statsStrip(view, side));
    card.appendChild(h('div.card-status'));
    if (opts.hpBar) {
      const hp = view.hp !== undefined ? view.hp : view.maxHp;
      const bar = h('div.card-hpbar.bar', null, h('div.bar-fill', { style: { width: `${Math.max(0, Math.min(100, 100 * hp / (view.maxHp || hp || 1)))}%` } }));
      const wrap = h('div.card-wrap', { class: `side-${side}` }, bar, card);
      return wrap;
    }
    return card;
  }

  // detail: art between the rails, the two plates over it, name / emblem / rarity / pips / level on the plates
  const art = h('div.card-art', null, artImage(view), arrowsLayer(view.dirs, view.healDirs, view.buffDirs));
  if (opts.pieces) art.appendChild(renderPieces(opts.pieces.owned, opts.pieces.total));
  const plates = h('div.card-plates', { 'aria-hidden': 'true' });
  const head = h('div.card-head', null,
    h('div.card-name.plate', null, view.name, stage > 0 ? h('span.plus', null, '+'.repeat(stage)) : null),
    h('div.card-emblem', { title: tribe }, sprite(TRIBE_SPRITES[tribe], { alt: tribe })));
  const foot = h('div.card-foot.panel-inset', null,
    h('div.card-rarity-row', null, h('span.card-rarity', null, rarityLabel(rarity)), renderPips(stage)),
    levelBar({ level: view.level || 1, levelCap: view.levelCap, xp: view.xp, xpToNext: view.xpToNext }));
  card.append(art, plates, head, foot);

  const wrap = h('div.card-detail-wrap', { class: `rarity-${rarity}` }, card);
  if (opts.showStats !== false) {
    const hasAbility = Boolean(view.abilityText);
    wrap.appendChild(h('div.card-detail-stats.panel', null,
      h('div.stat-row', null,
        h('span.stat-chip.attack', null, sprite(STAT_SPRITES.attack), h('span.num', null, fmt(view.attack || 0))),
        h('span.stat-chip.hp', null, sprite(STAT_SPRITES.hp), h('span.num', null, fmt(view.maxHp !== undefined ? view.maxHp : (view.hp || 0)))),
        h('span.stat-chip.mana', null, sprite(STAT_SPRITES.mana), h('span.num', null, fmt(view.mana || 0)))),
      h('p.ability-text', { class: !hasAbility && 'none' }, hasAbility ? view.abilityText : 'No ability.')));
  }
  if (opts.actions && opts.actions.length) {
    wrap.appendChild(h('div.card-detail-actions', null,
      opts.actions.map((a) => {
        const b = iconButton(a.icon, { onClick: a.onClick, ariaLabel: a.label, size: 'lg', className: `action-${a.icon}` });
        const img = b.querySelector('img');
        if (img && ACTION_SPRITES[a.icon]) { img.src = spriteUrl(ACTION_SPRITES[a.icon]); img.classList.add('sprite'); }
        return b;
      })));
  }
  return wrap;
}

/**
 * Empty deck slot (cardslot_simple), optionally locked (cardslotlocked).
 * @param {number} index
 * @param {{locked?: boolean, side?: 'top'|'bottom'}} [opts]
 * @returns {HTMLElement}
 */
export function renderEmptySlot(index, opts = {}) {
  return h('div.deck-slot', { class: [opts.locked && 'locked', opts.side && `side-${opts.side}`], dataset: { slot: String(index) }, 'aria-label': opts.locked ? `Slot ${index + 1} (locked)` : `Slot ${index + 1}` });
}

/**
 * Show / clear a status overlay on a battle card.
 * @param {HTMLElement} cardEl  the .card element (or .card-wrap)
 * @param {'daze'|'stun'|'suspend'|'sphere'|'dead'|null} status
 */
export function setCardStatus(cardEl, status) {
  const card = cardEl.classList.contains('card') ? cardEl : cardEl.querySelector('.card');
  if (!card) return;
  const layer = card.querySelector('.card-status');
  if (!layer) return;
  layer.className = 'card-status';
  while (layer.firstChild) layer.removeChild(layer.firstChild);
  card.classList.toggle('dead', status === 'dead');
  if (!status || status === 'dead') return;
  const icons = { daze: 'broken-sword', stun: 'rings', suspend: 'circles', sphere: 'sphere' };
  layer.classList.add(status);
  layer.appendChild(icon(icons[status]));
}

/** Set a band value (plain digits) and keep the small font for 5+ characters, as stat() does. */
function setStatText(numEl, text) {
  if (numEl.textContent === text) return;
  numEl.textContent = text;
  const chip = numEl.parentElement;
  if (chip && chip.classList) chip.classList.toggle('long', text.length >= 5);
}

/**
 * Update the HP shown on a battle card (band value and outside HP bar).
 * @param {HTMLElement} cardEl  .card or .card-wrap
 * @param {number} hp
 * @param {number} maxHp
 */
export function updateCardHp(cardEl, hp, maxHp) {
  const wrap = cardEl.classList.contains('card-wrap') ? cardEl : cardEl.parentElement;
  const card = cardEl.classList.contains('card') ? cardEl : cardEl.querySelector('.card');
  const val = card && card.querySelector('.card-stat.hp .num');
  // may go below 0 (overkill), as in the original; only the bar stops at empty
  if (val) setStatText(val, plainNumber(hp));
  const fill = wrap && wrap.querySelector && wrap.querySelector('.card-hpbar .bar-fill');
  if (fill) fill.style.width = `${Math.max(0, Math.min(100, 100 * hp / (maxHp || 1)))}%`;
}

/**
 * Update the attack value shown on a battle card.
 * @param {HTMLElement} cardEl
 * @param {number} attack
 */
export function updateCardAttack(cardEl, attack) {
  const card = cardEl.classList.contains('card') ? cardEl : cardEl.querySelector('.card');
  const val = card && card.querySelector('.card-stat.attack .num');
  if (val) setStatText(val, plainNumber(Math.max(0, attack)));
}
